import assert from 'node:assert/strict';
import { mkdir, mkdtemp, writeFile, readFile, rm, utimes, symlink, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { createFileServices } from '../native/storage/files.mjs';
import { createLockServices } from '../native/storage/locks.mjs';
import { createFileFunctions } from '../native/storage/file-functions.mjs';

test('native data files preserve bytes, lock writes, retain source assets and constrain cleanup', async t=>{
  const parent=fileURLToPath(new URL('../var/tests/',import.meta.url));await mkdir(parent,{recursive:true});const root=await mkdtemp(path.join(parent,'native-files-'));
  const source=path.join(root,'source'),state=path.join(root,'state');await mkdir(path.join(source,'gamedata/sql'),{recursive:true});await mkdir(state);
  await writeFile(path.join(source,'gamedata/sql/reset.sql'),'SELECT 1;');
  const locks=await createLockServices(state), otherLocks=await createLockServices(state);
  t.after(async()=>{await locks.close();await otherLocks.close();assert.ok(path.resolve(root).startsWith(path.resolve(parent)+path.sep));await rm(root,{recursive:true,force:true});});
  const files=await createFileServices({stateRoot:state,sourceRoot:source,locks:locks.locks,clock:()=>2000});
  const other=await createFileServices({stateRoot:state,sourceRoot:source,locks:otherLocks.locks,clock:()=>2000});
  assert.equal(await files.read('gamedata/sql/reset.sql'),'SELECT 1;');
  await assert.rejects(files.write('gamedata/sql/reset.sql','DROP'),/read-only/);
  await files.write('gamedata/tmp/news/one.dat','long original');await files.write('gamedata/tmp/news/one.dat','new');
  assert.equal(await files.read('gamedata/tmp/news/one.dat'),'new');
  const binary=Buffer.from([0,255,1,128]);await files.write('gamedata/replays/a.dat',binary,'wb');assert.deepEqual(await files.readBytes('gamedata/replays/a.dat'),binary);
  const globals=createFileFunctions(files);
  await globals.create_dir('gamedata/replays/extracted');assert.equal(await globals.is_dir('gamedata/replays/extracted'),true);
  await globals.chmod('gamedata/replays/a.dat',0o600);assert.equal(await globals.filesize('gamedata/replays/a.dat'),4);
  assert.deepEqual(await globals.gdir('gamedata/replays','dir'),['extracted']);
  await files.write('gamedata/replays/text.js','原始录像内容','wb');
  assert.equal(await globals.fold('gamedata/replays/extracted/game.dat',['gamedata/replays/a.dat','gamedata/replays/text.js']),'gamedata/replays/extracted/game.dat');
  assert.equal(await globals.unfold('gamedata/replays/extracted/game.dat'),1);
  assert.deepEqual(await files.readBytes('gamedata/replays/extracted/a.dat'),binary);assert.equal(await files.read('gamedata/replays/extracted/text.js'),'原始录像内容');
  await assert.rejects(globals.chmod('gamedata/sql/reset.sql',0o777),/read-only/);
  await assert.rejects(files.readText('gamedata/replays/a.dat'),/UTF-8/);
  await Promise.all([files.write('gamedata/tmp/news/append.dat','A','ab'),other.write('gamedata/tmp/news/append.dat','B','ab')]);
  assert.ok(['AB','BA'].includes(await files.read('gamedata/tmp/news/append.dat')));
  await files.touch('gamedata/tmp/news/one.dat');assert.equal(await files.mtime('gamedata/tmp/news/one.dat'),2000);
  await files.write('gamedata/tmp/news/.gitignore','keep').then(()=>assert.fail('hidden data file must be refused'),error=>assert.match(error.message,/path/));
  await writeFile(path.join(state,'gamedata/tmp/news/.gitignore'),'keep');
  await utimes(path.join(state,'gamedata/tmp/news/append.dat'),1000,1000);
  await files.clear('gamedata/tmp/news',{keepRoot:true,expireSeconds:100});
  assert.equal(await files.exists('gamedata/tmp/news/append.dat'),false);assert.equal(await files.exists('gamedata/tmp/news/one.dat'),true);
  assert.equal(await readFile(path.join(state,'gamedata/tmp/news/.gitignore'),'utf8'),'keep');
  await assert.rejects(files.clear('gamedata/tmp'),/subdirectory/);
  for(const name of ['../source/gamedata/sql/reset.sql','gamedata/tmp/../../native-install.json','C:/secret','gamedata/tmp/x:stream'])await assert.rejects(files.read(name));
  await symlink(source,path.join(state,'gamedata/tmp/outside'),'junction');
  await assert.rejects(files.read('gamedata/tmp/outside/gamedata/sql/reset.sql'),/symlink/);
  await assert.rejects(files.write('gamedata/tmp/outside/new.dat','bad'),/symlink/);
  await assert.rejects(files.clear('gamedata/tmp/outside'),/symlink/);
  assert.equal(await readFile(path.join(source,'gamedata/sql/reset.sql'),'utf8'),'SELECT 1;');
  assert.ok((await stat(path.join(state,'.native-locks'))).isDirectory());
});
