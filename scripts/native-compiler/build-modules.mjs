import PHP from 'php-parser';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ModuleEmitter, collectFunctions, signaturesFor } from './module-emitter.mjs';
import { hoistLiterals } from './hoist-literals.mjs';
import { optimizeInitializers } from './optimize-initializers.mjs';
import { selectImports } from './select-imports.mjs';
import { patchLiteralRows } from './patch-literal-rows.mjs';
import { transferOwnedReturns } from './transfer-owned-returns.mjs';
import { elideTemporaryCopies } from './elide-temporary-copies.mjs';

const project = fileURLToPath(new URL('../../', import.meta.url));
const parser = new PHP({ parser: { version: '7.4' }, ast: { withPositions: true } });
const digest = source => createHash('sha256').update(source).digest('hex');
export async function buildModules({ skillsOnly = true, remainingOnly = false } = {}) {
  const inventory = JSON.parse(await readFile(path.join(project, 'native/inventory.json'), 'utf8'));
  const asts = new Map(), signatures = {}, parseErrors = [];
  // Function declarations determine by-reference call sites, including the
  // boundary into manually ported modules. Nothing is executed during parsing.
  for (const module of inventory.modules) for (const file of module.code) {
    const source = await readFile(path.join(project, 'engine', file.source), 'utf8');
    try {
      const ast = parser.parseCode(source, file.source);
      asts.set(file.source, { ast, source }); Object.assign(signatures, signaturesFor(ast, module.name));
    } catch (error) { parseErrors.push({ module: module.name, source: file.source, error: error.message }); }
  }
  const outputs = [], failures = [], infoById = {};
  const manual = remainingOnly ? new Set([...(await import('../../native/catalog.mjs')).nativeGameplayModules.map(module => module.name), 'user_settings', 'team', 'itemshop', 'itemmix']) : new Set();
  const target = path.join(project, 'native/generated', remainingOnly ? 'remaining' : ''); await mkdir(path.join(target, 'modules'), { recursive: true });
  for (const module of inventory.modules.filter(value => remainingOnly ? !/^skill\d+$/.test(value.name) && !manual.has(value.name) : skillsOnly ? /^skill\d+$/.test(value.name) : value.name !== 'user_settings')) {
    try {
      const functions = module.code.flatMap(file => collectFunctions(asts.get(file.source)?.ast ?? { children: [] }));
      const localFunctions = new Set(functions.map(fn => fn.name.name.toLowerCase()));
      const definitions = [], top = [], calls = new Set();
      for (const file of module.code) {
        const parsed = asts.get(file.source); if (!parsed) throw new Error(`Cannot parse ${file.source}`);
        const emitter = new ModuleEmitter(file.source, { module: module.name, signatures, localFunctions });
        emitter.phase = 'top'; top.push(emitter.statement(parsed.ast));
        for (const fn of collectFunctions(parsed.ast)) definitions.push(emitter.emitFunction(fn));
        for (const call of emitter.calls) calls.add(call);
        const visit = node => {
          if (!node || typeof node !== 'object') return;
          if (node.kind === 'call' && node.what.kind === 'name' && node.what.name === 'define'
            && node.arguments[0]?.value === `MOD_${module.name.toUpperCase()}_INFO`) {
            if (node.arguments[1]?.kind !== 'string') throw new Error(`${file.source}: skill metadata is not an inert string`);
            infoById[module.name.slice(5)] = node.arguments[1].value;
          }
          for (const [key, value] of Object.entries(node)) if (key !== 'loc') visit(value);
        };
        visit(parsed.ast);
      }
      const metadata = { name: module.name, dependencies: module.dependencies, optionalDependencies: module.optionalDependencies, conflicts: module.conflicts };
      const names = [...localFunctions].filter(name => !['init', '___pre_init', '___post_init'].includes(name));
      const code = `// Static native migration of ${module.sourceRoot}; generated by build-modules.mjs.\nimport { cachedModuleContext as createModuleContext } from '${remainingOnly ? '../../' : '../'}context.mjs';\n${definitions.join('\n')}\nexport const definition = {\n  ...${JSON.stringify(metadata)},\n  state: () => Object.create(null),\n  async initialize(ctx) {\n    const r = createModuleContext(ctx, ${JSON.stringify(module.name)}, 'top'), s = ctx.state();\n${top.join('')}${localFunctions.has('init') ? '    await init(ctx);\n' : ''}  },\n  functions: { ${names.join(', ')} },\n};\nexport default definition;\n`;
      const valuesPath = remainingOnly ? '../../../templates/values.mjs' : '../../templates/values.mjs';
      const optimized = elideTemporaryCopies(transferOwnedReturns(optimizeInitializers(selectImports(hoistLiterals(patchLiteralRows(code, valuesPath), valuesPath)).code)));
      const output = `modules/${module.name}.mjs`; await writeFile(path.join(target, output), optimized);
      outputs.push({ module: module.name, output, generatedHash: digest(optimized), functions: names, calls: [...calls].sort(), sources: module.code.map(file => ({ source: file.source, hash: digest(asts.get(file.source).source) })) });
    } catch (error) { failures.push({ module: module.name, error: error.message }); }
  }
  const selectedSignatures = Object.fromEntries(Object.entries(signatures).filter(([name]) => outputs.some(output => name.startsWith(output.module + '.'))));
  await writeFile(path.join(project, 'native/generated/all-signatures.json'), JSON.stringify(signatures, null, 2) + '\n');
  await writeFile(path.join(target, 'signatures.json'), JSON.stringify(selectedSignatures, null, 2) + '\n');
  await writeFile(path.join(target, 'catalog.mjs'), `// Generated native module definitions; ordinary imported JavaScript only.\n${outputs.map((output, index) => `import m${index} from ${JSON.stringify('./' + output.output)};`).join('\n')}\nexport const definitions = [${outputs.map((_, index) => `m${index}`).join(', ')}];\nexport const infoById = ${JSON.stringify(infoById, null, 2)};\n`);
  const report = { outputs, failures, parseErrors };
  await writeFile(path.join(target, 'manifest.json'), JSON.stringify(report, null, 2) + '\n');
  return { modules: outputs.length, functions: outputs.reduce((sum, output) => sum + output.functions.length, 0), failures, parseErrors };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log(JSON.stringify(await buildModules({ skillsOnly: !process.argv.includes('--all'), remainingOnly: process.argv.includes('--remaining') }), null, 2));
