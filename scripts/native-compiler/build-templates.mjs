import PHP from 'php-parser';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { templateSource } from '../../native/templates/source.mjs';
import { TemplateEmitter } from './template-emitter.mjs';

const project = fileURLToPath(new URL('../../', import.meta.url));
export const parser = new PHP({ parser: { version: '7.4' }, ast: { withPositions: true } });
export function compileTemplate(source, filename, options) {
  const transformed = templateSource(source, options);
  const ast = parser.parseCode(transformed, filename);
  const emitter = new TemplateEmitter(filename);
  return { code: emitter.emit(ast), calls: [...emitter.calls].sort() };
}
function languageLiteral(node) {
  if (node.kind === 'string') return node.value;
  if (node.kind === 'array') return Object.fromEntries(node.items.map(item => [languageLiteral(item.key), languageLiteral(item.value)]));
  throw new Error(`Non-literal language configuration: ${node.kind}`);
}
export async function sourceLanguage() {
  const ast = parser.parseCode(await readFile(path.join(project, 'engine/templates/default/templates.lang.php'), 'utf8'));
  const assignment = ast.children.find(node => node.kind === 'expressionstatement' && node.expression.kind === 'assign' && node.expression.left.name === 'language');
  if (!assignment) throw new Error('Original language array is missing');
  return languageLiteral(assignment.expression.right);
}
export async function buildTemplates() {
  const manifest = JSON.parse(await readFile(path.join(project, 'upstream/manifest.json'), 'utf8'));
  const inventory = JSON.parse(await readFile(path.join(project, 'native/inventory.json'), 'utf8'));
  const language = await sourceLanguage(), target = path.join(project, 'native/templates'), outputs = [], failures = [];
  const names = Object.fromEntries(inventory.modules.flatMap(module => module.templates.map(filename => {
    const relative = filename.slice(module.sourceRoot.length, -4);
    return [`MOD_${module.name.toUpperCase()}_${relative.toUpperCase().replaceAll('/', '_')}`, { module: module.name, name: filename.slice(0, -4) }];
  })));
  for (const file of manifest.files.filter(file => /\.(htm|html)$/i.test(file.path))) {
    const source = await readFile(path.join(project, 'engine', file.path), 'utf8');
    let generated;
    try { generated = compileTemplate(source, file.path, { language }); }
    catch (error) { failures.push({ file: file.path, error: error.message }); continue; }
    const output = `generated/${file.path}.mjs`;
    await mkdir(path.dirname(path.join(target, output)), { recursive: true });
    await writeFile(path.join(target, output), generated.code);
    outputs.push({ source: file.path, sourceHash: file.sha256, output, generatedHash: createHash('sha256').update(generated.code).digest('hex'), calls: generated.calls });
  }
  if (failures.length) throw new Error(JSON.stringify(failures, null, 2));
  await writeFile(path.join(target, 'catalog.mjs'), `// Generated by scripts/native-compiler/build-templates.mjs.\nexport const names = ${JSON.stringify(names, null, 2)};\nexport const loaders = {\n${outputs.map(item => `  ${JSON.stringify(item.source)}: () => import(${JSON.stringify('./' + item.output)}),`).join('\n')}\n};\n`);
  await writeFile(path.join(target, 'manifest.json'), JSON.stringify({ sourceCommit: manifest.commit, outputs }, null, 2) + '\n');
  return { templates: outputs.length, bindings: Object.keys(names).length, calls: [...new Set(outputs.flatMap(file => file.calls))].sort() };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log(JSON.stringify(await buildTemplates(), null, 2));
