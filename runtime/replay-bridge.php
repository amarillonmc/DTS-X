<?php
/**
 * Preserve the daemon's replay response format for ordinary Node/WASM requests.
 * Load this from the trusted runtime bootstrap. Call dtsx_record_replay_response()
 * at the end of command.php, after command_act.php has saved the player's state.
 * The preparation patch also permits replay/post_gameover_events under
 * DTS_NODE_RUNTIME, while retaining all original archive-selection rules.
 */
if (!defined('DTS_NODE_RUNTIME') || DTS_NODE_RUNTIME !== true) {
    return;
}

function dtsx_record_replay_response()
{
    global $___MOD_SRV, $___MOD_CODE_ADV3, $page, $gametype, $replay_ignore_mode;
    global $gamedata, $jgamedata, $pid, $room_id, $room_prefix, $oprecorder;
    global $starttime, $moveut, $moveutmin, $pagestartime, $___MOD_TMP_FILE_DIRECTORY;

    if ($___MOD_SRV || !$___MOD_CODE_ADV3 || !defined('MOD_REPLAY')) return false;
    if (isset($page) && $page !== 'command') return false;
    if (in_array($gametype, (array) $replay_ignore_mode)) return false;
    if (!is_array($gamedata) || isset($gamedata['url']) || !is_string($jgamedata) || $jgamedata === '') return false;
    if ((int) $pid <= 0 || !isset($gamedata['innerHTML'])) return false;
    if (!function_exists('replay\\replay_record_op')) return false;

    // room_prefix is generated by the engine; it is distinct from room_id.
    // Match the original response and recording directory conventions exactly.
    $dtsxRoomPrefix = (string) $room_prefix;
    if (!preg_match('/^[a-zA-Z0-9_]*$/D', $dtsxRoomPrefix)) {
        throw new RuntimeException('Invalid replay room prefix.');
    }
    $dtsxResponseDir = rtrim($___MOD_TMP_FILE_DIRECTORY, '/\\') . '/' . (int) $room_id . '_/';
    $dtsxReplayDir = GAME_ROOT . 'gamedata/tmp/replay/' . $dtsxRoomPrefix . '_/' . (int) $pid;
    foreach (array($dtsxResponseDir, $dtsxReplayDir) as $dtsxDir) {
        if (!is_dir($dtsxDir) && !mkdir($dtsxDir, 0775, true) && !is_dir($dtsxDir)) {
            throw new RuntimeException('Cannot create replay directory.');
        }
    }

    $dtsxResponseFile = $dtsxResponseDir . 'node-' . bin2hex(random_bytes(12));
    if (file_put_contents($dtsxResponseFile, $jgamedata, LOCK_EX) === false) {
        throw new RuntimeException('Cannot persist replay response.');
    }
    $dtsxReplayFile = $dtsxReplayDir . '/replay.php';
    $dtsxElapsed = (float) $pagestartime - (float) $starttime + (float) $moveut * 3600 + (float) $moveutmin * 60;
    $dtsxLine = \replay\replay_record_op((string) $oprecorder) . ',' . $dtsxElapsed . ',' . $dtsxResponseFile . ",\n";
    $dtsxHandle = fopen($dtsxReplayFile, 'c+b');
    if ($dtsxHandle === false) {
        unlink($dtsxResponseFile);
        throw new RuntimeException('Cannot open replay index.');
    }
    try {
        if (!flock($dtsxHandle, LOCK_EX)) throw new RuntimeException('Cannot lock replay index.');
        if (fstat($dtsxHandle)['size'] === 0) {
            $dtsxLine = "<?php if(!defined('IN_GAME')) exit('Access Denied'); ?>\n" . $dtsxLine;
        }
        fseek($dtsxHandle, 0, SEEK_END);
        if (fwrite($dtsxHandle, $dtsxLine) !== strlen($dtsxLine)) {
            throw new RuntimeException('Cannot append replay index.');
        }
        fflush($dtsxHandle);
        flock($dtsxHandle, LOCK_UN);
    } finally {
        fclose($dtsxHandle);
    }
    return true;
}
